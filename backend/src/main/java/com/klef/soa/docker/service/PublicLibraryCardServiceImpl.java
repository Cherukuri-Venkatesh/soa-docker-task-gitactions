package com.klef.soa.docker.service;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;

import com.klef.soa.docker.dto.PublicLibraryCardDTO;
import com.klef.soa.docker.entity.PublicLibraryCard;
import com.klef.soa.docker.repository.PublicLibraryCardRepository;

@Service
public class PublicLibraryCardServiceImpl implements PublicLibraryCardService {

    @Autowired
    private PublicLibraryCardRepository libraryCardRepo;

    // Helper: Map Entity to DTO
    private PublicLibraryCardDTO mapToDTO(PublicLibraryCard entity) {
        if (entity == null) {
            return null;
        }
        return new PublicLibraryCardDTO(
            entity.getId(),
            entity.getCardNumber(),
            entity.getHolderName(),
            entity.getIssueDate(),
            entity.getActive()
        );
    }

    // Helper: Map DTO to Entity
    private PublicLibraryCard mapToEntity(PublicLibraryCardDTO dto) {
        if (dto == null) {
            return null;
        }
        PublicLibraryCard entity = new PublicLibraryCard();
        entity.setId(dto.getId());
        entity.setCardNumber(dto.getCardNumber());
        entity.setHolderName(dto.getHolderName());
        entity.setIssueDate(dto.getIssueDate());
        entity.setActive(dto.getActive());
        return entity;
    }

    @Override
    public PublicLibraryCardDTO addRecord(PublicLibraryCardDTO libraryCardDTO) {
        PublicLibraryCard entity = mapToEntity(libraryCardDTO);
        // ID is auto-generated by backend/database
        entity.setId(null);
        PublicLibraryCard saved = libraryCardRepo.save(entity);
        return mapToDTO(saved);
    }

    @Override
    public List<PublicLibraryCardDTO> displayAll() {
        List<PublicLibraryCard> cards = libraryCardRepo.findAll();
        List<PublicLibraryCardDTO> dtos = new ArrayList<>();
        for (PublicLibraryCard card : cards) {
            dtos.add(mapToDTO(card));
        }
        return dtos;
    }

    @Override
    public PublicLibraryCardDTO getById(Long id) {
        Optional<PublicLibraryCard> optionalCard = libraryCardRepo.findById(id);
        return optionalCard.map(this::mapToDTO).orElse(null);
    }

    @Override
    public PublicLibraryCardDTO updateRecord(Long id, PublicLibraryCardDTO libraryCardDTO) {
        Optional<PublicLibraryCard> optionalCard = libraryCardRepo.findById(id);
        if (optionalCard.isPresent()) {
            PublicLibraryCard existing = optionalCard.get();
            existing.setCardNumber(libraryCardDTO.getCardNumber());
            existing.setHolderName(libraryCardDTO.getHolderName());
            existing.setIssueDate(libraryCardDTO.getIssueDate());
            existing.setActive(libraryCardDTO.getActive());
            PublicLibraryCard updated = libraryCardRepo.save(existing);
            return mapToDTO(updated);
        }
        return null;
    }

    @Override
    public String deleteById(Long id) {
        if (libraryCardRepo.existsById(id)) {
            libraryCardRepo.deleteById(id);
            return "Public Library Card deleted successfully";
        }
        return null;
    }
}
